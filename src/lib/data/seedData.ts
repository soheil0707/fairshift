// Helper to generate 30 days of realistic shifts
function generateSeedShifts(): Shift[] {
  const shifts: Shift[] = [];
  const baseDate = new Date("2026-10-01T08:00:00Z");

  SEED_WORKERS.forEach((worker, workerIdx) => {
    // Generate 22 to 26 working days in the month
    for (let day = 1; day <= 26; day++) {
      const shiftDate = new Date(baseDate);
      shiftDate.setUTCDate(day);

      // Skip Sundays for standard workers (day % 7 === 0)
      if (day % 7 === 0 && workerIdx % 4 !== 0) {
        continue;
      }

      const shiftId = `shift-${worker.id}-${day}`;
      const isOvertimeShift = (workerIdx + day) % 5 === 0; // Some workers get overtime
      const isFatigueShift = worker.id === "w-suresh" && day >= 10 && day <= 17; // Suresh has consecutive days & long hours

      let startHour = 8;
      let durationHours = 8;

      if (isFatigueShift) {
        durationHours = 11.5; // >10h triggers fatigue!
      } else if (isOvertimeShift) {
        durationHours = 10.0; // 2h overtime
      }

      const checkIn = new Date(shiftDate);
      checkIn.setUTCHours(startHour, 0, 0, 0);

      const checkOut = new Date(checkIn.getTime() + durationHours * 60 * 60 * 1000);

      const regular = Math.min(8.0, durationHours);
      const overtime = Math.max(0, durationHours - 8.0);

      shifts.push({
        id: shiftId,
        workerId: worker.id,
        orgId: worker.orgId,
        checkInTime: checkIn.toISOString(),
        checkOutTime: checkOut.toISOString(),
        checkInMethod: day % 2 === 0 ? "qr_code" : "geofence",
        regularHours: regular,
        overtimeHours: overtime,
        status: "completed",
        notes: isOvertimeShift ? "Evening concrete pour OT" : undefined,
      });
    }
  });

  return shifts;
}

